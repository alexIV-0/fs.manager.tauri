// Фоновый синхронизатор: то, что делает зеркало зеркалом, а не просто списком.
//
// Без него всё в клиенте — ручное: скачать по двойному клику, залить кнопкой,
// вытеснить из настроек. Человек же ждёт от папки поведения гуглдиска: положил
// файл — уехал, не трогал четыре часа — освободилось место.
//
// ── Пульс вместо обхода ─────────────────────────────────────────────────────
// Раньше цикл раз в 15 секунд обходил всё зеркало рекурсивно и на каждый файл
// делал запрос в индекс — то есть платил обходом диска за то, чего в 99 % тиков
// не происходило. Теперь работа приходит СОБЫТИЕМ: очередь кандидатов
// (`pending.rs`) наполняется вотчером и явными вызовами раннера, а цикл её
// разгружает. Полный обход остался страховкой на редкий такт.
//
// Дисциплина цикла:
//   • задач ДВЕ: пульс (события, дельты, прогресс) и заливка байтов. Разделены
//     потому, что передача ждётся целиком, а пульс обязан биться дальше — иначе
//     большой файл замораживает синхронизацию и свой же значок (см. `start_uploads`);
//   • пульс короткий (3 с) — заливка начинается почти сразу после появления файла;
//   • тик не держит лок каталога дольше одной операции;
//   • за пульс заливаем ограниченное число файлов — иначе один большой архив
//     заблокирует очередь на часы и «синхронизация» станет незаметной;
//   • тяжёлое (сверка локальных правок, полный обход, вытеснение) идёт реже
//     заливки и на разных тактах, чтобы не сходиться в один пульс.

use std::sync::atomic::{AtomicBool, Ordering};
use std::time::Duration;

use tauri::Manager;

use super::config;
use super::evict::EvictionPolicy;
use super::StorageService;

/// Базовый такт. Всё остальное — кратности от него.
///
/// 3 секунды — компромисс: заливка начинается почти сразу после появления файла, а
/// живой прогресс обновляется достаточно часто, чтобы человек видел движение (для
/// файла на гигабайты этого хватает с запасом). Мельче такт означал бы лишние
/// запросы в индекс в покое, когда делать нечего.
const PULSE: Duration = Duration::from_secs(3);
/// Сколько пульсов подряд размер и mtime должны не меняться, чтобы файл,
/// найденный вотчером, считался дописанным. 2 пульса ≈ 6 секунд.
///
/// Явно помеченные раннером файлы этого не ждут вообще — там ожидание было бы
/// чистой потерей времени.
const QUIET_PULSES: u32 = 2;
/// Сколько файлов заливаем за один пульс.
const UPLOADS_PER_PULSE: usize = 4;
/// Сколько файлов массового скачивания везём одновременно.
///
/// Двух достаточно, и больше вредно: канал вниз один файл целиком не занимает
/// (задержка на подпись и открытие соединения), а с четырёх начинается спор за
/// диск и за лок каталога. Заливка остаётся строго по одному — уплинк уже, и
/// делить его между файлами обычно только замедляет.
const DOWNLOAD_WORKERS: usize = 2;
/// Как часто пустая очередь скачивания смотрит, не появилась ли работа.
///
/// Не пульс: человек нажал «скачать папку» и обязан увидеть движение сразу, а
/// три секунды тишины после нажатия читаются как «не сработало». Проверка стоит
/// один захват мьютекса, поэтому частота здесь бесплатна.
const DOWNLOAD_IDLE: Duration = Duration::from_millis(400);
/// Сверка локальных правок — раз в минуту (20 × 3 с).
const DETECT_EVERY: u32 = 20;
/// Обновление списка проектов — раз в 2 минуты (40 × 3 с).
///
/// Архив (`is_archived`) и пауза (`is_paused`) живут в `projects`, а **не в журнале
/// изменений**: дельты про них не рассказывают ничего. Значит «заархивировал на
/// сайте» без этого такта не доезжает до программы вообще — ни до значка, ни до
/// решения раннера «обрабатывать ли».
const PROJECTS_EVERY: u32 = 40;
/// Опрос дельт каталога — раз в 30 секунд (10 × 3 с).
///
/// Каталог обязан подтягиваться САМ: переименовали на сайте — у человека должно
/// поехать здесь, и наоборот. До этой правки `/delta` звали только в начале витка
/// обработки и из модалки «Информация», то есть при простое программа про облако не
/// узнавала ничего.
const DELTA_EVERY: u32 = 10;

/// Каждый 10-й пульс = раз в 30 секунд. Сайт считает машину онлайн, если последний
/// контакт свежее 90 секунд, — берём с тройным запасом, чтобы один пропущенный
/// запрос не гасил индикатор.
const PING_EVERY: u32 = 10;
/// Полный обход зеркала — раз в 10 минут (200 × 3 с).
///
/// Это страховка, а не механизм: файл, о котором никто не сообщил и который не
/// увидел вотчер (слежка не поднялась, событие потерялось на сетевом диске),
/// иначе не был бы залит никогда.
const FULL_SCAN_EVERY: u32 = 200;
/// Вытеснение — раз в 5 минут (100 × 3 с). Трогает диск, спешить ему некуда.
const EVICT_EVERY: u32 = 100;
/// Повторный полный `/tree` — раз в 10 минут, по тёплым проектам.
///
/// Нужен ровно для одного: увидеть чужое переименование. Бэкенд его не журналит, и
/// из дельт узнать о нём нельзя никак.
const RETREE_EVERY: u32 = 200;
/// Сколько проект считается тёплым после последнего касания.
///
/// Это и есть весь «ленивый режим»: работаешь с проектом — он синхронизируется;
/// перестал — через 15 минут выпадает из опроса сам. Никаких переключателей.
const WARM_WINDOW: Duration = Duration::from_secs(15 * 60);

/// Запустить цикл один раз на всё приложение.
///
/// Повторный вызов (переподключение, демо после живого) ничего не делает: цикл
/// сам смотрит на текущее состояние сервиса и просто простаивает, пока хранилище
/// не подключено.
pub fn start(app: tauri::AppHandle) {
    static STARTED: AtomicBool = AtomicBool::new(false);
    if STARTED.swap(true, Ordering::SeqCst) {
        return;
    }

    // Байты — отдельной задачей: пульс обязан продолжать биться, пока они едут.
    start_uploads(app.clone());
    start_downloads(app.clone());

    tauri::async_runtime::spawn(async move {
        let mut tick: u32 = 0;
        // Ревизия сейфа с прошлого пульса. `None` — ещё не спрашивали: первое
        // наблюдение только запоминается, иначе каждый запуск программы начинался
        // бы с пометки всех копий несвежими и лишнего похода за ключами.
        let mut known_vault_revision: Option<i64> = None;
        loop {
            tokio::time::sleep(PULSE).await;
            tick = tick.wrapping_add(1);

            let svc: tauri::State<'_, StorageService> = app.state();
            if !svc.is_attached().await {
                continue;
            }

            // Заливки здесь НЕТ: она живёт в своей задаче (`upload_loop`), иначе
            // пульс останавливался бы на всё время передачи.

            // Живой прогресс: пока передача идёт, её строку надо перечитывать. Байты
            // пишутся в `transfers` раз в 4 МБ, но интерфейс об этом сам не узнаёт —
            // без этого тика проценты не появлялись вовсе, и большой файл выглядел
            // как зависшая программа. Запрос дешёвый и в покое не находит ничего.
            match svc.active_transfer_paths().await {
                Ok(paths) if !paths.is_empty() => svc.emit_changed(&paths),
                Ok(_) => {}
                Err(e) => eprintln!("[storage] активные передачи: {e}"),
            }

            // Охват синхронизации — только тёплые проекты, то есть те, с которыми
            // работают. Открыл папку пользователя и зашёл в проект — он тёплый;
            // раннер взял проект в виток — тоже тёплый. Остальное молчит, и машине
            // обработки не приходится держать живой всю папку пользователя.
            if tick % DELTA_EVERY == 0 {
                if let Err(e) = delta_round(&svc).await {
                    eprintln!("[storage] дельты: {e}");
                }
            }

            // «Я на связи» — независимо от режима воркера. Иначе сайт слышит машину
            // только когда та спрашивает задачу, и состояние «программа запущена,
            // воркер выключен» неотличимо от «машину выключили».
            //
            // Ошибку глушим до строки в консоли: сайт может не знать про очередь
            // (старая сборка) или лежать, а пульс синхронизации из-за этого
            // останавливаться не должен.
            if tick % PING_EVERY == 0 {
                match svc.queue_ping().await {
                    // Ревизия сейфа приезжает попутным полем пульса. Разошлась с
                    // прошлой — на сайте правили секреты, и наши копии могли быть
                    // отозваны. Не удаляем их здесь: задача в работе не должна
                    // рваться на середине ролика (VENDOR_KEYS_CONTRACT.md §6.6).
                    // Помечаем несвежими — и ближайший запрос перед следующей
                    // задачей пойдёт за ключами заново, не полагаясь на `known`.
                    Ok(revision) => {
                        let changed = matches!(known_vault_revision, Some(prev) if prev != revision);
                        known_vault_revision = Some(revision);
                        if changed {
                            match crate::commands::vault_commands::mark_site_stale(&app) {
                                Ok(n) if n > 0 => {
                                    println!("[storage] ревизия сейфа {revision}: помечено копий {n}")
                                }
                                Ok(_) => {}
                                Err(e) => eprintln!("[storage] пометка копий сейфа: {e}"),
                            }
                        }
                    }
                    Err(e) => eprintln!("[storage] ping очереди: {e}"),
                }
            }

            if tick % PROJECTS_EVERY == 0 {
                if let Err(e) = projects_round(&svc).await {
                    eprintln!("[storage] список проектов: {e}");
                }
            }

            if tick % RETREE_EVERY == 0 {
                match svc.retree_warm(WARM_WINDOW).await {
                    Ok(n) if n > 0 => println!("[storage] перечитано деревьев: {n}"),
                    Ok(_) => {}
                    Err(e) => eprintln!("[storage] повторный обход: {e}"),
                }
            }

            // Правки уже известных файлов: без этого перерендер в тот же путь
            // получал бы значок «надо залить» и ждал ручного нажатия.
            if tick % DETECT_EVERY == 0 {
                if let Err(e) = detect_round(&svc).await {
                    eprintln!("[storage] сверка локальных правок: {e}");
                }
            }

            // Полный обход — по такту ИЛИ когда очередь призналась, что потеряла
            // картину (событий пришло больше, чем она способна держать).
            if tick % FULL_SCAN_EVERY == 0 || svc.take_pending_overflow() {
                if let Err(e) = full_scan_round(&svc).await {
                    eprintln!("[storage] полный обход: {e}");
                }
            }

            if tick % EVICT_EVERY == 0 {
                if let Err(e) = evict_round(&app, &svc).await {
                    eprintln!("[storage] вытеснение: {e}");
                }
            }
        }
    });
}

/// Залить то, о чём нам сообщили и что успокоилось.
/// Заливка байтов — СВОЯ задача, отдельно от пульса.
///
/// Так было не всегда, и цена ошибки оказалась высокой. `upload_round` ждёт каждую
/// передачу целиком, и пока он стоял в общем цикле, файл на 450 МБ останавливал
/// демон на минуты: не эмитился живой прогресс, не шли дельты, не обновлялся список
/// проектов — всё то, что и делает зеркало зеркалом.
///
/// Снаружи это выглядело особенно обманчиво: в модалке передач и в верхней панели
/// проценты бежали (они опрашивают Rust по таймеру, события им не нужны), а значок у
/// самого файла оставался «есть только локально» — потому что колонку никто не просил
/// перечитаться. То есть чем крупнее файл, тем надёжнее пропадал его значок.
///
/// Заливки остаются последовательными: параллелить их — отдельное решение (уплинк
/// один, и делить его между четырьмя файлами обычно вредно). Здесь важно лишь то,
/// что их ожидание больше не блокирует всё остальное.
fn start_uploads(app: tauri::AppHandle) {
    tauri::async_runtime::spawn(async move {
        loop {
            tokio::time::sleep(PULSE).await;

            let svc: tauri::State<'_, StorageService> = app.state();
            if !svc.is_attached().await {
                continue;
            }
            if let Err(e) = upload_round(&svc).await {
                eprintln!("[storage] заливка: {e}");
            }
        }
    });
}

/// Разгрузка очереди массового скачивания — своими задачами, не пульсом.
///
/// Причина та же, что у заливки: `ensure_local` ждёт файл целиком, и в общем цикле
/// один пятигиговый мастер остановил бы всю синхронизацию. Плюс здесь их несколько:
/// папка — это очередь, и пока один файл едет, второй может ехать тоже.
fn start_downloads(app: tauri::AppHandle) {
    for _ in 0..DOWNLOAD_WORKERS {
        let app = app.clone();
        tauri::async_runtime::spawn(async move {
            loop {
                let svc: tauri::State<'_, StorageService> = app.state();
                if !svc.is_attached().await {
                    tokio::time::sleep(PULSE).await;
                    continue;
                }
                let Some(path) = svc.take_download() else {
                    tokio::time::sleep(DOWNLOAD_IDLE).await;
                    continue;
                };
                // Ошибка одного файла очередь не останавливает: недоступный файл,
                // протухшая подпись, обрыв — обычное дело, а остальные должны уехать.
                // Счётчик неудач видно в интерфейсе, поэтому молчания здесь нет.
                let ok = match svc.ensure_local(&path).await {
                    Ok(_) => true,
                    Err(e) => {
                        eprintln!("[storage] папкой не скачан {}: {e}", path.display());
                        false
                    }
                };
                svc.finish_download(ok);
            }
        });
    }
}

async fn upload_round(svc: &StorageService) -> Result<(), String> {
    for path in svc.take_upload_candidates(QUIET_PULSES, UPLOADS_PER_PULSE) {
        // Кандидат ≠ повод заливать. Вотчер видит и наши собственные записи, и
        // без этой проверки только что скачанный файл поехал бы обратно в облако.
        match svc.needs_upload(&path).await {
            Ok(true) => {}
            Ok(false) => continue,
            Err(e) => {
                eprintln!("[storage] не проверен {}: {e}", path.display());
                continue;
            }
        }
        // Ошибка одного файла не должна останавливать остальные: битые права или
        // занятый файл — обычное дело, а очередь идёт дальше.
        if let Err(e) = svc.upload_local(&path).await {
            eprintln!("[storage] не залит {}: {e}", path.display());
        }
    }
    Ok(())
}

/// Перечитать список проектов: имена, архив, пауза, состав.
///
/// Эмитим событие только когда что-то изменилось: интерфейс перечитывает колонки по
/// нему, и дёргать его каждые две минуты «на всякий случай» значило бы мигать
/// списком без причины.
async fn projects_round(svc: &StorageService) -> Result<(), String> {
    let before = svc.projects_fingerprint().await?;
    {
        let mut g = svc.sync_mut().await;
        let Some(s) = g.as_mut() else { return Ok(()) };
        s.refresh_projects().await.map_err(|e| e.to_string())?;
    }
    svc.refresh_dirs().await;
    let after = svc.projects_fingerprint().await?;
    if before != after {
        println!("[storage] список проектов изменился");
        svc.emit_projects_changed();
    }
    Ok(())
}

/// Догнать каталог по ТЁПЛЫМ проектам и подвинуть локальные копии.
///
/// Тёплый — тот, с которым работали последние `WARM_WINDOW`. Проект, до которого не
/// дотрагивались, не опрашивается вовсе: он подтянется при первом обращении.
///
/// **Оговорка про бэкенд:** переименования он сейчас в журнал не пишет
/// (`writeRename` журналит только при смене ключа, а ключ при переименовании не
/// меняется), поэтому чужое переименование придёт к нам не дельтой, а только полным
/// `/tree`. Просьба записана — `STORAGE_BACKEND_REQUESTS.md`, пункт 1.8. Наша часть
/// готова: как только события появятся, они применятся этим же циклом.
async fn delta_round(svc: &StorageService) -> Result<(), String> {
    let projects = svc.warm_projects(WARM_WINDOW);
    for pid in projects {
        if let Err(e) = svc.catch_up_project(&pid).await {
            eprintln!("[storage] дельта {pid}: {e}");
        }
    }
    // Логический путь мог измениться — двигаем локальные копии следом. Без этого
    // сверка не найдёт файл на старом месте и объявит его «только в облаке».
    match svc.reconcile_local_paths().await {
        Ok(n) if n > 0 => println!("[storage] локальных копий переехало: {n}"),
        Ok(_) => {}
        Err(e) => eprintln!("[storage] сверка путей: {e}"),
    }
    Ok(())
}

/// Найти локально изменённые копии и поставить их в очередь на заливку.
///
/// Метку `LocalModified` ставит `detect_local_changes`, но сама она ничего не
/// заливает: очередь работает с путями. Конфликты (`Conflict`) сюда не попадают
/// по построению — `detect_local_change` их не трогает, и решение остаётся за
/// человеком.
async fn detect_round(svc: &StorageService) -> Result<(), String> {
    let changed = svc.detect_local_changes().await?;
    if changed == 0 {
        return Ok(());
    }
    let paths = svc.local_modified_paths().await?;
    let n = svc.mark_dirty(&paths, true);
    if n > 0 {
        println!("[storage] локально изменено файлов: {n} — поставлены на заливку");
    }
    // Сказать интерфейсу ОБЯЗАТЕЛЬНО. Без этого правка файла в зеркале не меняла на
    // экране ничего: метка `LocalModified` появлялась в индексе, но строка колонки
    // оставалась с прежней галочкой. Через несколько секунд файл заливался, значок
    // возвращался в «синхронизировано» — и человек не видел ни одного изменения,
    // хотя всё сработало. А если заливка падала, он не видел и проблемы.
    svc.emit_changed(
        &paths
            .iter()
            .map(|p| p.to_string_lossy().to_string())
            .collect::<Vec<_>>(),
    );
    Ok(())
}

/// Страховка: обойти зеркало и добрать всё, о чём никто не сообщил.
async fn full_scan_round(svc: &StorageService) -> Result<(), String> {
    // Ограничение то же, что у пульса заливки: обход не должен превращаться в
    // лавину передач, очередь разберёт найденное следующими пульсами.
    let found = svc.pending_uploads(UPLOADS_PER_PULSE * 8).await?;
    if found.is_empty() {
        return Ok(());
    }
    // `ready = true`: файл лежит на диске давно (мы дошли до него обходом, а не по
    // событию), ждать от него затишья бессмысленно.
    let n = svc.mark_dirty(&found, true);
    println!("[storage] полный обход нашёл незалитых файлов: {n}");
    Ok(())
}

async fn evict_round(app: &tauri::AppHandle, svc: &StorageService) -> Result<(), String> {
    let dir = app
        .path()
        .app_data_dir()
        .map_err(|e| format!("app_data_dir: {e}"))?;
    let cfg = config::load(&dir);

    // Настройки могли поменяться между тиками — читаем их каждый раз, а не
    // запоминаем при старте.
    let policy = EvictionPolicy {
        ttl_hours: cfg.keep_hours_or_default(),
        max_bytes: Some(cfg.max_mirror_gb_or_default() as i64 * 1024 * 1024 * 1024),
        hot_patterns: cfg.hot_patterns_or_default(),
    };
    let report = svc.run_eviction(policy).await?;
    if report.evicted > 0 {
        println!(
            "[storage] вытеснено файлов: {}, освобождено байт: {}",
            report.evicted, report.freed_bytes
        );
    }
    Ok(())
}
