// Полосы прогонов — независимые раннеры, которые НЕ должны задевать друг друга.
//
// Обработка, постинг и режим воркера запускаются отдельными кнопками, живут по своим
// часам и могут работать одновременно. При этом делили ровно две вещи, и обе —
// процессные синглтоны: набор семафоров (`ResourcePool`) и флаг прерывания в Rust.
// Из-за первого обработка могла подвиснуть навсегда, из-за второго — постинг
// наследовал чужой стоп, а стоп обработки убивал ffmpeg постинга.
//
// Почему полоса — ИМЯ, а не случайный id прогона. Обработка исполняется в realm'е
// NODE_WIN, а кнопка Stop есть и в MAIN_WIN; окна — разные JS-realm'ы и общего
// состояния у них нет. Случайный id пришлось бы синхронизировать между окнами
// событием, тогда как фиксированное имя знают оба сразу. Отдельные прогоны ОДНОГО
// раннера различать не нужно: параллельно он себя не запускает.

export const RUN_PROCESSING = 'processing';
export const RUN_POSTING = 'posting';
/** Режим воркера: задачи из очереди сайта. Своя полоса, но пулы делит с обработкой. */
export const RUN_WORKER = 'worker';

export type RunLane = typeof RUN_PROCESSING | typeof RUN_POSTING | typeof RUN_WORKER;

/**
 * Область ресурсных пулов: какой полосе с кем делить семафоры.
 *
 * ПОЛОСА и ОБЛАСТЬ ПУЛОВ — разные вещи, и у воркера они намеренно разошлись.
 *
 * Полоса отвечает на вопрос «чей стоп меня убивает»: у локального прогона и воркера
 * они разные, иначе Stop локальной обработки прибивал бы ffmpeg взятой из очереди
 * задачи, а аварийный стоп воркера — наоборот.
 *
 * Область пулов отвечает на вопрос «сколько тяжёлого крутится НА МАШИНЕ». Лимит
 * `local: 1` («afterEffect, moho, whisper — одно за раз») — про железо, а не про
 * раннер: два набора семафоров дали бы два одновременных рендера AE на одном
 * компьютере, ровно то, что этот лимит и запрещает. Поэтому воркер садится в тот же
 * набор, что локальный прогон, и его шаг честно ждёт свободный слот.
 *
 * Постинг остаётся при своём наборе: он почти целиком `online` (отправил-ждёшь),
 * локальных ресурсов не ест и в очереди за AE стоять не должен.
 */
const POOL_SCOPE: Record<string, string> = {
	[RUN_PROCESSING]: RUN_PROCESSING,
	[RUN_WORKER]: RUN_PROCESSING,
	[RUN_POSTING]: RUN_POSTING,
};

/** Набор семафоров, к которому относится полоса. Незнакомая полоса живёт сама по себе. */
export function poolScopeOf(lane: string): string {
	return POOL_SCOPE[lane] ?? lane;
}
