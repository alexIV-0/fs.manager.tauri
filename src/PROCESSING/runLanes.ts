// Полосы прогонов — два независимых раннера, которые НЕ должны задевать друг друга.
//
// Обработка и постинг запускаются отдельными кнопками, живут по своим часам и могут
// работать одновременно. При этом делили ровно две вещи, и обе — процессные
// синглтоны: набор семафоров (`ResourcePool`) и флаг прерывания в Rust. Из-за
// первого обработка могла подвиснуть навсегда, из-за второго — постинг наследовал
// чужой стоп, а стоп обработки убивал ffmpeg постинга.
//
// Почему полоса — ИМЯ, а не случайный id прогона. Обработка исполняется в realm'е
// NODE_WIN, а кнопка Stop есть и в MAIN_WIN; окна — разные JS-realm'ы и общего
// состояния у них нет. Случайный id пришлось бы синхронизировать между окнами
// событием, тогда как фиксированное имя знают оба сразу. Отдельные прогоны ОДНОГО
// раннера различать не нужно: параллельно он себя не запускает.

export const RUN_PROCESSING = 'processing';
export const RUN_POSTING = 'posting';

export type RunLane = typeof RUN_PROCESSING | typeof RUN_POSTING;
