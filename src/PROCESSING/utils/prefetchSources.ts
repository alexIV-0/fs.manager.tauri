// Префетч исходников: качаем то, что понадобится следующим.
//
// ── Зачем ───────────────────────────────────────────────────────────────────
// Очередь строится целиком заранее (`findAllFilesForProcess`), то есть уже известно,
// какие файлы потребуются. Без префетча каждый элемент честно ждёт свои минуты
// скачивания по очереди; с ним ожидание случается один раз в начале, а дальше файлы
// уже на диске.
//
// ── Почему это безопасно ────────────────────────────────────────────────────
// `ensureLocal` в Rust — single-flight по файлу: когда до элемента дойдёт настоящая
// очередь, он не начнёт вторую передачу, а дождётся этой же. Значит худшее, что
// может сделать префетч, — скачать файл, который потом не понадобился (виток
// прервали). Файл при этом ложится в зеркало и вытесняется по TTL, как любой другой.
//
// Вне зеркала весь модуль ничего не делает: `ensureLocal` для локального пути
// возвращает его как есть, без единого IPC-вызова.

import { useWorkProject_Store } from '@/Store/Processing/useWorkProject_Store';
import { ensureLocal } from '@/Utils/storageSeam';

/** Сколько элементов вперёд тянем. Три — как в плане (раздел 9). */
const AHEAD = 3;

/** Уже отданные в префетч пути: повторно дёргать их незачем. */
const asked = new Set<string>();

/** Исходник элемента — то, что обработка откроет первым делом. */
function sourceOf(item: any): string | undefined {
	const p = item?.description?.pathForDelete;
	return typeof p === 'string' && p ? p : undefined;
}

/**
 * Поставить в очередь скачивание исходников следующих элементов.
 *
 * Не ждёт и не бросает: префетч — ускорение, и если он не удался, обычная гидрация
 * на своём месте всё равно скачает файл (и покажет внятную ошибку, если не сможет).
 */
export async function prefetchNextItems(): Promise<void> {
	const queue = useWorkProject_Store.getState().workProject;
	if (queue.length === 0) return;

	for (const item of queue.slice(0, AHEAD)) {
		const src = sourceOf(item);
		if (!src || asked.has(src)) continue;
		asked.add(src);
		try {
			// Последовательно, а не пачкой: три параллельных мастера отобрали бы полосу
			// у файла, который нужен прямо сейчас.
			await ensureLocal(src);
		} catch {
			// Молча: настоящая попытка будет на своём месте.
		}
	}
}

/** Забыть отданные пути — на старте нового витка. */
export function resetPrefetch(): void {
	asked.clear();
}
