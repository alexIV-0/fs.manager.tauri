import path from 'path';
// =========================================================================================
/**
 * Очищает имя файла от эмоджи и специальных символов, удаляет расширение
 * Сохраняет только буквы, цифры, пробелы и символы: []()._-
 * Возвращает очищенное имя без расширения
 */
// =========================================================================================
export function clearFileName(fileName: string): string {
    // Удаляем расширение файла
    const nameWithoutExtension = path.basename(fileName, path.extname(fileName));

    // Удаляем все символы кроме букв, цифр, пробелов и разрешенных символов: []()._-
    const cleanedName = nameWithoutExtension.replace(/[^\p{L}\p{N}\s\[\]()._\-]/gu, '');

    // Нормализуем пробелы и обрезаем края
    return cleanedName.replace(/\s+/g, ' ').trim();
}
