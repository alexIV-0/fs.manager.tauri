// ====================================================================
// чистим имя файла от «мусора»: оставляем буквы (любых алфавитов),
// цифры, пробелы и пунктуацию [ ] ( ) . _ - ; режем символы и эмоджи.
//
// ВАЖНО: движок ExtendScript (ES3) не понимает \p{L}/\p{N} и флаг /u,
// поэтому whitelist Unicode-букв регуляркой невозможен. Идём посимвольно.
// ====================================================================
export function cleanName(name: string): string {
	var out = '';
	for (var i = 0; i < name.length; i++) {
		var ch = name.charAt(i);
		var code = name.charCodeAt(i);

		// суррогатные пары — почти все современные эмоджи 🎉🚀 (астральные плоскости)
		if (code >= 0xd800 && code <= 0xdfff) {
			continue;
		}

		// разрешённая пунктуация и пробел
		if (ch == ' ' || ch == '[' || ch == ']' || ch == '(' || ch == ')' || ch == '.' || ch == '_' || ch == '-') {
			out += ch;
			continue;
		}

		// ASCII-буквы и цифры (0-9, A-Z, a-z)
		if ((code >= 48 && code <= 57) || (code >= 65 && code <= 90) || (code >= 97 && code <= 122)) {
			out += ch;
			continue;
		}

		// не-ASCII буквы (кириллица, латиница с диакритикой, греческий, CJK, …):
		// оставляем, но вырезаем BMP-блоки символов/значков/стрелок/пиктограмм.
		if (code >= 0x00c0) {
			var isSymbol =
				(code >= 0x2000 && code <= 0x2bff) || // пунктуация, стрелки, мат.символы, значки, дингбаты
				(code >= 0x2e00 && code <= 0x2e7f) || // дополнительная пунктуация
				(code >= 0x3000 && code <= 0x303f) || // CJK-символы и пунктуация
				(code >= 0xfe00 && code <= 0xfe0f) || // variation selectors (модификаторы эмоджи)
				code >= 0xfff0; // спецсимволы
			if (!isSymbol) {
				out += ch;
			}
			continue;
		}

		// всё прочее (ASCII-символы ! @ # $ % ^ & * + = ` ~ { } ; : ' " , < > / \ | ?,
		// управляющие коды, Latin-1 символы ©®°± и т.п.) — выкидываем.
	}
	return out;
}
